<section>
    <h3 class="font-extrabold text-ink-950">Para que serve?</h3>
    <p class="mt-2">Esta tela transforma sua tabela atual de Silk em um cálculo automático por quantidade de peças e número de cores, sem exigir que você entenda regras técnicas.</p>
</section>

<section class="rounded-2xl bg-app p-4">
    <h3 class="font-extrabold text-ink-950">Exemplo real</h3>
    <p class="mt-2">Um pedido de 20 peças com 2 cores usa a célula “20 a 49 / 2 cores”. Se houver base branca configurada como cor adicional, o sistema procura a coluna de 3 cores.</p>
</section>

<section>
    <h3 class="font-extrabold text-ink-950">O que significa cada parte?</h3>
    <dl class="mt-3 space-y-3">
        <div><dt class="font-bold text-ink-900">Tabela por quantidade e cores</dt><dd>O valor de cada célula é o preço cobrado por peça.</dd></div>
        <div><dt class="font-bold text-ink-900">Preparação por tela/cor</dt><dd>Valor separado para matriz, emulsão, gravação, registro e limpeza. Pode ficar incluído no preço por peça.</dd></div>
        <div><dt class="font-bold text-ink-900">Base branca</dt><dd>Pode contar como uma cor, virar um adicional por peça ou não alterar o preço automaticamente.</dd></div>
        <div><dt class="font-bold text-ink-900">Tintas e efeitos</dt><dd>Adicionais opcionais para Plastisol, Puff, Metalizado e outros processos que você já cobra diferente.</dd></div>
    </dl>
</section>

<section>
    <h3 class="font-extrabold text-ink-950">O que ainda não é analisado?</h3>
    <p class="mt-2">Nesta etapa, o EstampaFlow registra sua tabela comercial. Depois do cadastro de tinta, emulsão, tela, mão de obra e perdas, será possível comparar o preço cobrado com o custo real.</p>
</section>

<section class="rounded-2xl border border-brand-200 bg-brand-50 p-4">
    <h3 class="font-extrabold text-ink-950">Regra importante</h3>
